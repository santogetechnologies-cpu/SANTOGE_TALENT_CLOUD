function buildSapMiniGame(spec: RawSapLesson): MiniGameConfig {
  const diff = spec.day <= 15 ? 1 : spec.day <= 30 ? 2 : spec.day <= 60 ? 3 : spec.day <= 75 ? 4 : 5;

  if (spec.gameKind === "match") {
    const pairs = spec.matchPairs
      ? spec.matchPairs.map(([left, right]) => ({ left, right }))
      : [
          { left: "SPRO", right: "Customizing IMG" },
          { left: "ACDOCA", right: "Universal Journal" },
          { left: "FS00", right: "G/L Master Centrally" },
          { left: "F110", right: "Automatic Payment Program" },
        ];
    return matchGame(
      spec.gameType,
      spec.gameTitle,
      `Match each SAP organizational or transactional concept to its correct financial role for ${spec.title}.`,
      diff,
      pairs,
    );
  }

  if (spec.gameKind === "predict") {
    return predictGame(
      spec.gameType,
      spec.gameTitle,
      spec.predictScenario ?? `// SAP Transaction Execution Simulation - Day ${spec.day}\nPosting transaction for ${spec.title}`,
      spec.predictOptions ?? [
        spec.mcqCorrect,
        spec.mcqWrong[0] ?? "Option A",
        spec.mcqWrong[1] ?? "Option B",
        spec.mcqWrong[2] ?? "Option C",
      ],
      spec.predictOptions && spec.predictAnswer ? Math.max(0, spec.predictOptions.indexOf(spec.predictAnswer)) : 0,
      spec.predictExpl ?? spec.mcqExpl,
      diff,
    );
  }

  if (spec.gameKind === "arrange") {
    const steps = spec.arrangeSteps ?? [
      "Define organizational master structure",
      "Assign accounting parameters and field status",
      "Post operational financial documents to ACDOCA",
      "Generate statutory financial statements and audit reports",
    ];
    return arrangeGame(
      spec.gameType,
      spec.gameTitle,
      spec.arrangeGoal ?? `Arrange the SAP FICO configuration or execution steps in correct operational sequence for: ${spec.title}.`,
      steps.map((step, idx) => ({
        id: `sap-block-${idx + 1}`,
        code: `${idx + 1}. ${step}`,
        order: idx + 1,
      })),
      diff,
    );
  }

  if (spec.gameKind === "error") {
    return errorGame(
      spec.gameType,
      spec.gameTitle,
      spec.errorSnippet ?? `// SAP Customizing & Posting Diagnostics - Day ${spec.day}\n// ${spec.title}\nTABLE ACDOCA {\n  // Error condition on Day ${spec.day}\n  RAISE_EXCEPTION("Out of balance or missing cost object");\n}`,
      [
        { line: 4, description: spec.errorBug ?? "Missing mandatory cost center or segment assignment" },
        { line: 2, description: "Posting key field status conflict with G/L field status group" },
      ],
      diff,
    );
  }

  if (spec.gameKind === "pipeline") {
    const nodes = spec.pipelineNodes ?? [
      ["step_1", "Configuration in SPRO", "Org Structure Setup", "Config"],
      ["step_2", "Master Data Setup", "G/L, BP, Cost Center", "Master"],
      ["step_3", "Universal Journal Entry", "ACDOCA Line Item Posting", "Post"],
      ["step_4", "Statutory Reporting", "Balance Sheet & P&L", "Report"],
    ];
    return pipelineGame(
      spec.gameType,
      spec.gameTitle,
      `Assemble the SAP financial architecture pipeline stages in correct execution sequence for ${spec.title}.`,
      nodes.map((n) => n[1]),
      [0, 1, 2, 3],
      diff,
    );
  }

  return fillBlanksGame(
    spec.gameType,
    spec.gameTitle,
    spec.fillTemplate ?? `In SAP S/4HANA, financial transactions update {{1}} and managerial costs flow to {{2}}.`,
    [
      {
        placeholder: "ACDOCA",
        answer: "ACDOCA",
        options: ["ACDOCA", "BSEG", "COEP"],
      },
    ],
    diff,
  );
}

